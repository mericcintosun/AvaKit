// The eerc-token template proves in the browser with circuit files of
// ava-labs/EncryptedERC at one commit (CIRCUIT_COMMIT in lib/eerc-config.ts),
// and `npm run deploy:eerc` deploys the contracts of a commit
// (COMMIT in scripts/deploy-eerc.mjs) with that repository's own
// scripts/deploy-standalone.ts. A proof the app makes is accepted only by a
// verifier that carries the verification key of the proving key it was made
// with, so this checks:
//
// 1. the two constants name the same commit, the one
//    contracts-ci/upstream/EncryptedERC/sources.json pins;
// 2. the SHA-256 lib/eerc-config.ts pins for each circuit file is the one
//    sources.json recorded from that file at that commit, so a pin moved
//    without new hashes fails here and not in the app;
// 3. deploy-standalone.ts deploys the production verifiers: every
//    `deployVerifiers(...)` call in its code (comments aside) is
//    `deployVerifiers(<signer>, true)`, and test/helpers.ts takes those from
//    contracts/prod/. (Before 2026-08-31 it deployed the generated ones in
//    contracts/verifiers/, whose keys match none of the circuit files and were
//    made without a phase-2 contribution: they rejected every real proof and
//    would have accepted forged ones.)
// 4. each production verifier, contracts/prod/<Name>Verifier.sol, carries
//    exactly the key in circom/build/<name>/<name>_verification_key.json,
//    which sits next to the proving key the app downloads, and that key's
//    delta is not its gamma: a key with delta = gamma (no phase-2
//    contribution) accepts a forged proof for any statement.
//
// The upstream files of 3 and 4 are read with upstream.mjs's pinnedFile(), so
// each is checked against the git blob id sources.json gives it, whether it
// comes from GitHub or from the cache: a stale or edited cached copy is never
// read. A file that cannot be fetched is reported as such (`unreachable`), not
// as drift: what needed it was not compared.
//
// With `circuits: true` it also downloads the ten circuit files (about 55 MB,
// not cached) and checks each against its blob id and its pinned SHA-256.
//
// Moving the pin: point both constants at the new commit, then
//   node scripts/eerc-pin.mjs pin
// rewrites sources.json from that commit's git tree (GitHub's API: set
// GITHUB_TOKEN past its anonymous rate limit), downloading each circuit file
// whose blob changed to record its SHA-256, and prints the hashes
// lib/eerc-config.ts then needs. Finish with
//   node scripts/check-artifacts.mjs --eerc-circuits

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  blobId,
  download,
  FetchError,
  githubJson,
  pinnedBytes,
  pinnedFile,
  rawUrl,
  readPin,
  UPSTREAM_DIR,
  withoutComments,
} from "./upstream.mjs";

const NAME = "EncryptedERC"; // its directory in contracts-ci/upstream/
const REPOSITORY = "ava-labs/EncryptedERC";
const PIN = `contracts-ci/upstream/${NAME}/sources.json`;
const TEMPLATE = "packages/create-avalanche-app/templates/eerc-token";
const CONFIG = `${TEMPLATE}/lib/eerc-config.ts`;
const DEPLOY = `${TEMPLATE}/scripts/deploy-eerc.mjs`;
const DEPLOY_SCRIPT = "scripts/deploy-standalone.ts";
const HELPERS = "test/helpers.ts";
const ABOUT =
  "The files of ava-labs/EncryptedERC that scripts/eerc-pin.mjs reads, at the commit the eerc-token template pins (CIRCUIT_COMMIT and COMMIT), each by its git blob id; and each circuit file the template's app downloads from circom/build/ at that commit, by blob id and SHA-256. Generated by: node scripts/eerc-pin.mjs pin";

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const byPath = (a, b) => a.localeCompare(b);

/** What the template pins: the commit its app proves with, the commit its
 * deploy script builds, and each circuit file (its path under circom/build/)
 * with the SHA-256 the app checks it against. */
function readTemplate(repoRoot) {
  const config = readFileSync(join(repoRoot, CONFIG), "utf8");
  const deploy = readFileSync(join(repoRoot, DEPLOY), "utf8");
  const circuits = [
    ...config.matchAll(/(?:wasm|zkey): \{ path: "([^"]+)", sha256: "([0-9a-f]{64})" \}/g),
  ].map(([, path, hash]) => ({ path, sha256: hash }));
  return {
    commit: config.match(/^const CIRCUIT_COMMIT = "([0-9a-f]{40})";$/m)?.[1],
    deployed: deploy.match(/^const COMMIT = "([0-9a-f]{40})";$/m)?.[1],
    circuits,
    // Each circuit by name: the directory its files sit in.
    names: [...new Set(circuits.map(({ path }) => path.split("/")[0]))],
  };
}

/** The production verifier of the circuit `name`, and its verification key. */
const verifierOf = (name) => `contracts/prod/${name[0].toUpperCase()}${name.slice(1)}Verifier.sol`;
const keyFileOf = (name) => `circom/build/${name}/${name}_verification_key.json`;

/** Every upstream file the check reads, the circuit files aside. */
const filesRead = (names) => [
  DEPLOY_SCRIPT,
  HELPERS,
  ...names.flatMap((name) => [verifierOf(name), keyFileOf(name)]),
];

/** The numeric constants a Solidity verifier declares, by name. */
function constants(source) {
  const found = new Map();
  const code = withoutComments(source);
  for (const [, name, value] of code.matchAll(/uint256\s+constant\s+(\w+)\s*=\s*(\d+)\s*;/g)) {
    found.set(name, value);
  }
  return found;
}

/** The key a snarkjs Solidity verifier embeds. Its G2 points are written
 * x1 = x[1], x2 = x[0], y1 = y[1], y2 = y[0] of the JSON key's coordinates. */
function keyOfVerifier(source) {
  const c = constants(source);
  const g2 = (name) => [`${name}x1`, `${name}x2`, `${name}y1`, `${name}y2`].map((k) => c.get(k));
  const ic = [];
  for (let i = 0; c.has(`IC${i}x`); i++) ic.push([c.get(`IC${i}x`), c.get(`IC${i}y`)]);
  return {
    alpha: [c.get("alphax"), c.get("alphay")],
    beta: g2("beta"),
    gamma: g2("gamma"),
    delta: g2("delta"),
    ic,
  };
}

/** The same key from a snarkjs verification_key.json. */
function keyOfJson(json) {
  const g2 = (point) => [point[0][1], point[0][0], point[1][1], point[1][0]];
  return {
    alpha: [json.vk_alpha_1[0], json.vk_alpha_1[1]],
    beta: g2(json.vk_beta_2),
    gamma: g2(json.vk_gamma_2),
    delta: g2(json.vk_delta_2),
    ic: json.IC.map((point) => [point[0], point[1]]),
  };
}

const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

/**
 * Check the pin of eerc-token in the repo at `repoRoot`. Returns
 * `{ commit, notes, problems, unreachable }`: what was checked, what is wrong
 * with the pin, and the downloads that failed (both empty when the pin was
 * checked and is sound).
 */
export async function checkEercPin(repoRoot, { circuits = false } = {}) {
  const notes = [];
  const problems = [];
  const unreachable = [];
  const template = readTemplate(repoRoot);
  const { commit } = template;
  const result = () => ({ commit, notes, problems, unreachable });
  if (!commit || !template.deployed) {
    problems.push(`${CONFIG} needs a CIRCUIT_COMMIT and ${DEPLOY} a COMMIT, each a full commit id`);
    return result();
  }
  if (commit !== template.deployed) {
    problems.push(
      `CIRCUIT_COMMIT (${CONFIG}) is ${commit} but COMMIT (${DEPLOY}) is ${template.deployed}: ` +
        "the app would prove with one version and deploy another",
    );
  }

  let pin;
  try {
    pin = readPin(NAME);
  } catch (error) {
    problems.push(`${PIN} cannot be read (${error.message})`);
    return result();
  }
  const top = pin.repositories?.find((repository) => repository.path === "");
  if (top?.commit !== commit) {
    problems.push(
      `${PIN} pins ${top?.commit}, but CIRCUIT_COMMIT is ${commit}: ` +
        "run `node scripts/eerc-pin.mjs pin` (see its header) when the pin moves",
    );
    return result();
  }

  // The hashes the app checks, against the ones taken from the files.
  const recorded = pin.circuits ?? {};
  if (template.circuits.length === 0) problems.push(`${CONFIG} pins no circuit files`);
  for (const { path, sha256: hash } of template.circuits) {
    const entry = recorded[path];
    if (entry === undefined) {
      problems.push(
        `${PIN} records no circom/build/${path}: run \`node scripts/eerc-pin.mjs pin\``,
      );
    } else if (entry.sha256 !== hash) {
      problems.push(
        `${CONFIG} pins sha256 ${hash} for ${path}, but circom/build/${path} at ${commit} has ` +
          `${entry.sha256} (${PIN}): the app would refuse the file`,
      );
    }
  }
  for (const path of Object.keys(recorded)) {
    if (!template.circuits.some((circuit) => circuit.path === path)) {
      problems.push(
        `${PIN} records circom/build/${path}, which ${CONFIG} does not pin: ` +
          "run `node scripts/eerc-pin.mjs pin`",
      );
    }
  }

  try {
    // One at a time: when GitHub cannot be reached, the first failure ends it.
    const text = async (path) => (await pinnedFile(NAME, path, pin)).toString("utf8");
    const script = withoutComments(await text(DEPLOY_SCRIPT));
    const calls = [...script.matchAll(/\bdeployVerifiers\s*\(([^)]*)\)/g)].map(([, args]) => args);
    if (calls.length === 0 || !calls.every((args) => /^\s*\w+\s*,\s*true\s*,?\s*$/.test(args))) {
      problems.push(
        `${DEPLOY_SCRIPT} at ${commit} does not deploy the production verifiers ` +
          "(not every call in its code is `deployVerifiers(<signer>, true)`): what it deploys " +
          "is not checked against the circuits",
      );
    }
    const helpers = withoutComments(await text(HELPERS));
    if (!/from\s+"\.\.\/typechain-types\/factories\/contracts\/prod"/.test(helpers)) {
      problems.push(
        `${HELPERS} at ${commit} no longer takes its production verifiers from contracts/prod`,
      );
    }

    for (const name of template.names) {
      const verifier = keyOfVerifier(await text(verifierOf(name)));
      const json = keyOfJson(JSON.parse(await text(keyFileOf(name))));
      if (!same(verifier, json)) {
        const differing = Object.keys(json).filter((part) => !same(verifier[part], json[part]));
        problems.push(
          `${verifierOf(name)} at ${commit} does not carry the key of ` +
            `circom/build/${name} (${differing.join(", ")} differ): it would reject the app's proofs`,
        );
      } else if (same(json.delta, json.gamma)) {
        problems.push(
          `the ${name} key at ${commit} has delta = gamma (no phase-2 contribution): ` +
            "a verifier with it accepts forged proofs",
        );
      } else {
        notes.push(`${name}: ${verifierOf(name)} carries the key of circom/build/${name}`);
      }
    }

    if (circuits) {
      for (const { path, sha256: hash } of template.circuits) {
        const bytes = await download(rawUrl(top, `circom/build/${path}`));
        const [blob, got] = [blobId(bytes), sha256(bytes)];
        if (blob !== recorded[path]?.blob) {
          problems.push(
            `circom/build/${path} at ${commit} has blob ${blob}, ${PIN} says ${recorded[path]?.blob}`,
          );
        } else if (got !== hash) {
          problems.push(
            `circom/build/${path} at ${commit} has sha256 ${got}, the pin says ${hash}`,
          );
        } else {
          notes.push(`${path}: sha256 matches the pin`);
        }
      }
    }
  } catch (error) {
    // A failed download compared nothing; any other failure is the pin's.
    (error instanceof FetchError ? unreachable : problems).push(error.message);
  }
  return result();
}

/** Rewrite sources.json from the commit the template pins (see the header). */
async function pin(repoRoot) {
  const template = readTemplate(repoRoot);
  const { commit } = template;
  if (!commit || commit !== template.deployed) {
    throw new Error(`point CIRCUIT_COMMIT (${CONFIG}) and COMMIT (${DEPLOY}) at one commit first`);
  }
  let previous = {};
  try {
    previous = readPin(NAME);
  } catch {
    // the first pin
  }
  const top = { path: "", repository: REPOSITORY, commit };
  const tree = await githubJson(`repos/${REPOSITORY}/git/trees/${commit}?recursive=1`);
  if (tree.truncated) throw new Error(`${REPOSITORY}: the tree at ${commit} is too big to list`);
  const blobs = new Map(
    tree.tree.filter((entry) => entry.type === "blob").map((entry) => [entry.path, entry.sha]),
  );
  const blobOf = (path) => {
    const id = blobs.get(path);
    if (id === undefined) throw new Error(`${path} is not a file of ${REPOSITORY} at ${commit}`);
    return id;
  };

  const files = {};
  for (const path of filesRead(template.names).sort(byPath)) {
    files[path] = blobOf(path);
    await pinnedBytes(top, path, files[path]); // fetched, checked against the tree, cached
  }
  const circuits = {};
  for (const path of template.circuits.map((circuit) => circuit.path).sort(byPath)) {
    const blob = blobOf(`circom/build/${path}`);
    // The same blob is the same bytes: only a file that changed is downloaded.
    const known = previous.circuits?.[path];
    let hash = known?.blob === blob ? known.sha256 : undefined;
    if (hash === undefined) {
      const bytes = await download(rawUrl(top, `circom/build/${path}`));
      if (blobId(bytes) !== blob) {
        throw new Error(`circom/build/${path}: the download does not match the git tree`);
      }
      hash = sha256(bytes);
    }
    circuits[path] = { blob, sha256: hash };
  }

  // JSON.stringify's layout is the one biome keeps: nothing to reformat.
  const file = join(UPSTREAM_DIR, NAME, "sources.json");
  const next = { about: ABOUT, repositories: [top], files, circuits };
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, `${JSON.stringify(next, null, 2)}\n`);
  console.log(
    `pinned ${Object.keys(files).length} files and ${Object.keys(circuits).length} circuit ` +
      `files of ${REPOSITORY} @ ${commit.slice(0, 12)} in ${file}`,
  );
  const stale = template.circuits.filter(
    ({ path, sha256: hash }) => circuits[path].sha256 !== hash,
  );
  if (stale.length > 0) {
    console.log(`Put these SHA-256 values in ${CONFIG}:`);
    for (const { path } of stale) console.log(`  ${path}: ${circuits[path].sha256}`);
  }
  console.log("Now: node scripts/check-artifacts.mjs --eerc-circuits");
}

// Run as a script, not imported:
//   node scripts/eerc-pin.mjs [--circuits]   check the pin
//   node scripts/eerc-pin.mjs pin            rewrite sources.json (see the header)
// Real paths on both sides: a temporary directory is often reached through a
// symlink (/var -> /private/var on macOS), and import.meta.url is resolved.
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const repoRoot = resolve(fileURLToPath(import.meta.url), "..", "..", "..");
  const args = process.argv.slice(2);
  if (args[0] === "pin") {
    await pin(repoRoot).catch((error) => {
      console.error(`PIN FAILED: ${error.message}`);
      process.exit(1);
    });
  } else {
    const { commit, notes, problems, unreachable } = await checkEercPin(repoRoot, {
      circuits: args.includes("--circuits"),
    });
    for (const note of notes) console.log(`ok ${note}`);
    for (const problem of problems) console.error(`EERC PIN DRIFT: ${problem}`);
    for (const message of unreachable) console.error(`EERC PIN: ${message}`);
    const sound = problems.length === 0 && unreachable.length === 0;
    if (sound) console.log(`ok eerc-token pin ${REPOSITORY}@${commit}`);
    process.exit(sound ? 0 : 1);
  }
}
